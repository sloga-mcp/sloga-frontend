    // APNs registration callbacks. UIKit delivers these to the app delegate
    // and nowhere else, so without this forwarding the Capacitor push plugin
    // never sees a device token and registration hangs forever with no error.
    func application(_ application: UIApplication,
                     didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(
